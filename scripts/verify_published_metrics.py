#!/usr/bin/env python
"""Assert the conclusions the README publishes still hold.

Every figure, table and number in README.md is generated by the pipeline, so the
readme can only go stale if the pipeline's output changes underneath it. This script is
the guard: it re-derives the published values from ``outputs/metrics.json`` and fails
loudly if any of them has moved.

Run it locally after any dependency change, and in CI on every push.

    python scripts/verify_published_metrics.py
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

#: Values quoted in README.md. Changing a README number means changing this too.
PUBLISHED = {
    "n_observations": 22,
    "n_features": 8,
    "null_cells": 0,
    "duplicate_rows": 0,
    "k_selected": 5,
    "k_recommended": 5,
    "silhouette": 0.14598450827748213,
    "total_wcss": 112.04496709087753,
    "points_below_zero": 5,
    "share_below_zero": 0.22727272727272727,
    "silhouette_k6": 0.0633,
    "ari_k5_vs_k6": 0.8189655172413793,
    "nmi_k5_vs_k6": 0.8942894536772479,
    "pca_cumulative": 0.5092,
    "kmeans_seed_min_ari": 0.6427,
    "kmeans_min_centroid_distance": 1.5532,
    "single_linkage_ari": 0.0296,
    "preferred_linkage_ari": 0.4484,
    "cluster_a_mean_silhouette": -0.0339,
    "cluster_b_mean_silhouette": 0.4299,
    "cluster_a_below_zero": 3,
    "cluster_b_below_zero": 0,
}

TOLERANCE = 1e-6


def check(metrics: dict) -> list[str]:
    failures: list[str] = []

    def expect(label, actual, expected, tol=TOLERANCE):
        if abs(actual - expected) > tol:
            failures.append(f"{label}: expected {expected}, got {actual}")

    meta = metrics["meta"]
    quality = metrics["quality"]
    primary = metrics["primary"]
    separation = primary["separation"]
    recommendation = metrics["k_recommendation"]

    expect("n_observations", meta["n_observations"], PUBLISHED["n_observations"])
    expect("n_features", len(meta["features"]), PUBLISHED["n_features"])
    expect("null_cells", quality["null_cells"], PUBLISHED["null_cells"])
    expect("duplicate_rows", quality["duplicate_rows"], PUBLISHED["duplicate_rows"])

    expect("k_selected", meta["k_selected"], PUBLISHED["k_selected"])
    expect("k_recommended", recommendation["recommended"], PUBLISHED["k_recommended"])
    if recommendation["votes"]["silhouette"] != PUBLISHED["k_selected"]:
        failures.append("silhouette index no longer selects the published k")
    if recommendation["votes"]["calinski_harabasz"] != PUBLISHED["k_selected"]:
        failures.append("Calinski-Harabasz no longer selects the published k")

    expect("silhouette", separation["silhouette"], PUBLISHED["silhouette"])
    expect("total_wcss", primary["fit"]["total"], PUBLISHED["total_wcss"])
    expect("points_below_zero", separation["points_below_zero"], PUBLISHED["points_below_zero"])
    expect("share_below_zero", separation["share_below_zero"], PUBLISHED["share_below_zero"])

    if primary["names"] != ["Arizona", "Madison", "Nevada", "New England", "Southern"]:
        failures.append(f"medoids changed: {primary['names']}")
    if primary["sizes"] != [5, 4, 2, 7, 4]:
        failures.append(f"cluster sizes changed: {primary['sizes']}")
    if sum(primary["sizes"]) != PUBLISHED["n_observations"]:
        failures.append("clusters no longer partition the dataset")

    agreement = {row["k"]: row for row in metrics["sensitivity"]["agreement_with_primary"]}
    expect("ari_k5_vs_k6", agreement[6]["ari"], PUBLISHED["ari_k5_vs_k6"])
    expect("nmi_k5_vs_k6", agreement[6]["nmi"], PUBLISHED["nmi_k5_vs_k6"])

    expect(
        "pca_cumulative", metrics["pca"]["cumulative_explained_variance"],
        PUBLISHED["pca_cumulative"], tol=5e-4,
    )

    contrast = metrics["kmeans_contrast"]
    expect("kmeans_seed_min_ari", contrast["kmeans_seed_min_ari"],
           PUBLISHED["kmeans_seed_min_ari"], tol=5e-4)
    expect("kmeans_min_centroid_distance", contrast["min_distance_point_to_own_centroid"],
           PUBLISHED["kmeans_min_centroid_distance"], tol=5e-4)
    if contrast["centroid_is_observation"] is not False:
        failures.append("K-Means centroid is no longer distinct from an observation")

    if metrics["seed_sensitivity"]["seed_independent"] is not True:
        failures.append("the segmentation is no longer seed-independent")

    cross = metrics["cross_linkage_agreement"]
    if not cross:
        failures.append("no cross-linkage agreement was computed")
    else:
        for pair, scores in cross.items():
            if abs(scores["ari"] - 1.0) > TOLERANCE:
                failures.append(f"{pair} no longer agree exactly (ARI {scores['ari']})")

    linkages = {row["linkage"]: row for row in metrics["linkages"]}
    expect(
        "single_linkage_ari", linkages["single"]["ari"],
        PUBLISHED["single_linkage_ari"], tol=5e-5,
    )
    for method in ("complete", "average", "ward"):
        expect(f"{method}_linkage_ari", linkages[method]["ari"],
               PUBLISHED["preferred_linkage_ari"], tol=5e-5)

    quality = metrics.get("segmentation_quality")
    if not quality:
        failures.append("no per-segment quality table was computed")
    else:
        expect("cluster_0 mean silhouette", quality["cluster_0"]["mean_silhouette"],
               PUBLISHED["cluster_a_mean_silhouette"], tol=5e-4)
        expect("cluster_1 mean silhouette", quality["cluster_1"]["mean_silhouette"],
               PUBLISHED["cluster_b_mean_silhouette"], tol=5e-4)
        expect("cluster_0 members below zero", quality["cluster_0"]["members_below_zero"],
               PUBLISHED["cluster_a_below_zero"])
        expect("cluster_1 members below zero", quality["cluster_1"]["members_below_zero"],
               PUBLISHED["cluster_b_below_zero"])

    return failures


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "metrics", nargs="?", type=Path,
        default=REPO_ROOT / "outputs" / "metrics.json",
        help="path to metrics.json",
    )
    args = parser.parse_args(argv)

    if not args.metrics.exists():
        print(f"error: {args.metrics} not found. Run `python scripts/run_analysis.py` first.")
        return 2

    metrics = json.loads(args.metrics.read_text(encoding="utf-8"))
    failures = check(metrics)

    if failures:
        print(f"FAILED: {len(failures)} published value(s) no longer hold\n")
        for failure in failures:
            print(f"  - {failure}")
        print("\nIf these changed legitimately, update PUBLISHED in this script "
              "and the README together.")
        return 1

    print(f"OK: all {len(PUBLISHED)} published values reproduce exactly.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
